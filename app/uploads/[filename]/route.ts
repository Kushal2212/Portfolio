import { NextResponse } from "next/server";
import { stat } from "fs/promises";
import { createReadStream } from "fs";
import { Readable } from "stream";
import path from "path";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

// SVG is intentionally absent: it can execute script when opened directly.
const TYPES: Record<string, string> = {
  jpg: "image/jpeg",
  jpeg: "image/jpeg",
  png: "image/png",
  webp: "image/webp",
  mp4: "video/mp4",
  m4v: "video/x-m4v",
  webm: "video/webm",
  mov: "video/quicktime",
};

/**
 * Serve local media uploads from disk. Files written to public/uploads after a
 * production build are not part of the build snapshot, so a small route keeps
 * local storage working without Cloudinary. Filenames are generated by the
 * upload route (no slashes or traversal).
 *
 * Range requests are supported so videos can be scrubbed without downloading
 * the whole file.
 */
export async function GET(
  request: Request,
  { params }: { params: Promise<{ filename: string }> },
) {
  const { filename } = await params;
  const ext = filename.split(".").pop()?.toLowerCase() ?? "";
  if (!/^[a-z0-9][a-z0-9-]*\.[a-z0-9]+$/i.test(filename) || !TYPES[ext]) {
    return new NextResponse("Not found", { status: 404 });
  }

  const filePath = path.join(process.cwd(), "public", "uploads", filename);
  let size: number;
  try {
    const info = await stat(filePath);
    if (!info.isFile()) throw new Error("Not a file");
    size = info.size;
  } catch {
    return new NextResponse("Not found", { status: 404 });
  }

  const commonHeaders = {
    "Content-Type": TYPES[ext],
    "Cache-Control": "public, max-age=31536000, immutable",
    "Accept-Ranges": "bytes",
  };

  const range = request.headers.get("range");
  if (!range) {
    const stream = createReadStream(filePath);
    return new NextResponse(Readable.toWeb(stream) as unknown as ReadableStream, {
      headers: { ...commonHeaders, "Content-Length": String(size) },
    });
  }

  const match = /^bytes=(\d*)-(\d*)$/.exec(range.trim());
  if (!match || (!match[1] && !match[2])) {
    return new NextResponse("Range not satisfiable", {
      status: 416,
      headers: { "Content-Range": `bytes */${size}` },
    });
  }

  let start: number;
  let end: number;
  if (!match[1]) {
    // Suffix range: `bytes=-500` means the last 500 bytes.
    const suffix = Number(match[2]);
    start = Math.max(size - suffix, 0);
    end = size - 1;
  } else {
    start = Number(match[1]);
    end = match[2] ? Number(match[2]) : size - 1;
  }

  if (!Number.isFinite(start) || !Number.isFinite(end) || start > end || start >= size) {
    return new NextResponse("Range not satisfiable", {
      status: 416,
      headers: { "Content-Range": `bytes */${size}` },
    });
  }

  end = Math.min(end, size - 1);
  const stream = createReadStream(filePath, { start, end });
  return new NextResponse(Readable.toWeb(stream) as unknown as ReadableStream, {
    status: 206,
    headers: {
      ...commonHeaders,
      "Content-Range": `bytes ${start}-${end}/${size}`,
      "Content-Length": String(end - start + 1),
    },
  });
}
